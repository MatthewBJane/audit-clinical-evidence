"""Generate a deterministic TikZ 'glitch band' for the ACE PDF cover.

Coordinates are in cm relative to (current page.center). A4 is 21 x 29.7,
so the page runs x = -10.5..10.5; the band bleeds to +-11. The band spans
y = BAND_LO..BAND_HI. Everything stays within REACH cm of the page edges, so
the title area (|x| < 10.5 - REACH) is always clear.

Visual grammar (mirrors the Rubik Glitch wordmark):
  * "notches": horizontal slices of the band edge shifted inward, leaving a
    white gap at the page edge with cyan/magenta ghosts beside the black;
  * "shards": black strips protruding above/below the band from the page edge;
  * "fringes": thin cyan/magenta bars hugging the band inside its edges;
  * "debris": small fragments floating above/below the band.
"""
import random

random.seed(2026001)

BAND_LO, BAND_HI = -1.7, 3.4
CYAN, MAG = "acecyan", "acemagenta"
REACH = 2.3            # max distance the glitch reaches in from the page edge (cm)

out = [r"% --- ACE glitch band (generated by scripts/gen_cover_band.py; change the seed there to reroll) ---",
       r"\fill[black] (-11,%.2f) rectangle (11,%.2f);" % (BAND_LO, BAND_HI),
       r"\fill[%s] (-11,%.2f) rectangle (11,%.2f);" % (CYAN, BAND_HI, BAND_HI + 0.07),
       r"\fill[%s] (-11,%.2f) rectangle (11,%.2f);" % (MAG, BAND_LO - 0.07, BAND_LO)]


def rect(x0, x1, y0, y1, color):
    out.append(r"\fill[%s] (%.2f,%.2f) rectangle (%.2f,%.2f);" % (color, min(x0, x1), y0, max(x0, x1), y1))


def pick(weights):
    pool = [c for c, w in weights for _ in range(w)]
    return random.choice(pool)


for side in (-1, 1):
    edge = 10.5 * side          # visible page edge
    bleed = 11 * side

    # --- notches: slices of the band shifted inward -------------------------
    ys = sorted(random.uniform(BAND_LO + 0.2, BAND_HI - 0.2) for _ in range(5))
    for y in ys:
        h = random.uniform(0.1, 0.32)
        if y + h > BAND_HI - 0.1:
            continue
        w = random.uniform(0.8, REACH)                # slice length from page edge
        dx = random.uniform(0.25, 0.8)                # inward shift (white gap)
        x_in = edge - side * w
        rect(bleed, x_in, y, y + h, "white")          # erase the slice (to the bleed)
        rect(edge - side * dx, x_in - side * dx, y, y + h, "black")   # shifted slice
        # chromatic split inside the gap: magenta at the page edge, cyan against the black
        g1 = random.uniform(0.05, 0.14)
        g2 = random.uniform(0.05, 0.14)
        rect(bleed, edge - side * g1, y, y + h, MAG)
        rect(edge - side * (dx - g2), edge - side * dx, y, y + h, CYAN)

    # --- shards: strips protruding outside the band --------------------------
    for top in (True, False):
        for _ in range(3):
            w = random.uniform(0.5, REACH)
            h = random.uniform(0.07, 0.22)
            off = random.uniform(0.04, 0.55)
            y0 = BAND_HI + off if top else BAND_LO - off - h
            x_in = edge - side * w
            c = pick((("black", 5), (CYAN, 3), (MAG, 3)))
            rect(bleed, x_in, y0, y0 + h, c)
            if c == "black" and random.random() < 0.7:  # chromatic fringe on black shards
                g = random.uniform(0.1, 0.3)
                rect(bleed, x_in - side * g, y0 + h, y0 + h + 0.04, CYAN)
                rect(bleed, x_in + side * g, y0 - 0.04, y0, MAG)

    # --- fringes: thin coloured bars inside the band near its edge -----------
    for _ in range(3):
        w = random.uniform(0.4, 1.6)
        h = random.uniform(0.04, 0.08)
        y = random.uniform(BAND_LO + 0.2, BAND_HI - 0.2)
        x0 = edge - side * random.uniform(0.0, REACH - 1.6)
        rect(x0, x0 - side * w, y, y + h, pick(((CYAN, 1), (MAG, 1))))

    # --- debris: small fragments floating above/below ------------------------
    for _ in range(2):
        w = random.uniform(0.2, 0.9)
        h = random.uniform(0.04, 0.1)
        x0 = side * random.uniform(10.5 - REACH, 10.2)
        y = random.choice((BAND_HI + random.uniform(0.7, 1.3), BAND_LO - random.uniform(0.7, 1.3)))
        rect(x0, x0 + side * w, y, y + h, pick((("black", 4), (CYAN, 3), (MAG, 3))))

print("\n".join(out))
