#!/usr/bin/env python3
"""Assemble the ACE Handbook chapters from the site pages.

Runs before every render (project: pre-render in _quarto.yml). It takes the
body of about.qmd, team.qmd, disclaimers.qmd and riv.qmd, strips each file's
front matter, turns the page into a chapter, and writes the result to
_handbook/<name>.md, which handbook.qmd pulls in with {{< include >}} and
renders to docs/handbook.pdf. Nothing is written by hand twice: edit the
pages, render the site, and the handbook follows.

Adjustments made for print:
  * raw HTML blocks are dropped by the PDF writer anyway; the team photo is
    replaced by a plain image so it survives;
  * the inline ORCID badges (raw <a><svg>) become plain links;
  * links between the four pages (about.qmd, riv.qmd, ...) become links to
    the corresponding chapter inside the handbook.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "_handbook"

CHAPTERS = [
    # (source, chapter title, chapter id)
    ("about.qmd", "About", "about"),
    ("team.qmd", "Team", "team"),
    ("disclaimers.qmd", "Disclaimers", "disclaimers"),
    ("riv.qmd", "Research Integrity Violations", "riv"),
]
IDS = {src: cid for src, _, cid in CHAPTERS}


def strip_front_matter(text: str) -> str:
    m = re.match(r"^---\n.*?\n---\n", text, re.S)
    return text[m.end():] if m else text


def convert(src: str, title: str, cid: str) -> str:
    body = strip_front_matter((ROOT / src).read_text(encoding="utf-8"))

    # team photo: replace the hover-photo HTML with a plain image
    body = re.sub(r"```\{=html\}\n<div class=\"ace-hover-photo\">.*?</div>\n```\n",
                  "![](images/about_photo.png){width=32%}\n", body, flags=re.S)
    # inline ORCID badge -> plain link
    body = re.sub(r'<a class="ace-orcid" href="([^"]+)"[^>]*>.*?</a>', r"[ORCID](\1)", body, flags=re.S)
    # links between the handbook's own pages -> chapter anchors
    for other, other_id in IDS.items():
        body = body.replace(f"]({other})", f"](#{other_id})")
        body = body.replace(f"](/{other.replace('.qmd', '.html')})", f"](#{other_id})")
        body = body.replace(f"]({other.replace('.qmd', '.html')})", f"](#{other_id})")
    return (f"<!-- GENERATED by scripts/build_handbook.py from {src}; edit that file, not this one. -->\n\n"
            f"# {title} {{#{cid}}}\n\n{body.strip()}\n")


def main():
    OUT.mkdir(exist_ok=True)
    for src, title, cid in CHAPTERS:
        (OUT / (Path(src).stem + ".md")).write_text(convert(src, title, cid), encoding="utf-8")
    print(f"handbook: {len(CHAPTERS)} chapters written to {OUT.relative_to(ROOT)}/")


if __name__ == "__main__":
    main()
